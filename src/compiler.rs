pub fn resolve_service_allow_set(
    svc: &Service,
    config: &Config,
    state: Option<&AppState>,
) -> Vec<String> {
    if let Some(st) = state {
        st.expand_allow_elements(&svc.allow, &config.global_allow)
    } else {
        let mut set = BTreeSet::new();
        for entry in config.global_allow.iter().chain(svc.allow.iter()) {
            if let Some(cidr) = expand_ip_wildcard_to_cidr(entry) {
                set.insert(cidr);
            }
        }
        set.into_iter().collect()
    }
}

pub fn resolve_gateway_allow_set(
    gw: &Gateway,
    config: &Config,
    state: Option<&AppState>,
) -> Vec<String> {
    if let Some(st) = state {
        st.expand_allow_elements(&gw.allow, &config.global_allow)
    } else {
        let mut set = BTreeSet::new();
        for entry in config.global_allow.iter().chain(gw.allow.iter()) {
            if let Some(cidr) = expand_ip_wildcard_to_cidr(entry) {
                set.insert(cidr);
            }
        }
        set.into_iter().collect()
    }
}

/// Compiles a Config (using current health/drain runtime state and resolved wildcard/hostname allow-lists
/// from AppState) into an atomic nftables ruleset string.
pub fn compile_nft_ruleset(config: &Config, state: Option<&AppState>) -> String {
    let mut out = String::new();
    out.push_str("#!/usr/sbin/nft -f\n");
    out.push_str("# Generated by nfty — L4 Service Load Balancer & Port Router\n\n");

    out.push_str("table ip nfty\n");
    out.push_str("delete table ip nfty\n\n");
    out.push_str("table ip nfty {\n");

    // 1. Emit dynamic rate-limit meters & allowlist sets per service
    for svc in config.services.values() {
        let id = svc.nft_id();
        let has_allow_rules = !svc.allow.is_empty() || !config.global_allow.is_empty();
        if has_allow_rules {
            let elements = resolve_service_allow_set(svc, config, state);
            let raw_rules: Vec<&String> = config.global_allow.iter().chain(svc.allow.iter()).collect();
            out.push_str(&format!(
                "    # allow-list rules for service {}: {:?}\n",
                svc.key, raw_rules
            ));
            out.push_str(&format!("    set allow_{} {{\n", id));
            out.push_str("        type ipv4_addr\n");
            out.push_str("        flags interval\n");
            if !elements.is_empty() {
                out.push_str(&format!(
                    "        elements = {{ {} }}\n",
                    elements.join(", ")
                ));
            }
            out.push_str("    }\n\n");
        }

        if let Some(limit) = &svc.limit {
            if limit.per_ip {
                out.push_str(&format!("    set meter_{} {{\n", id));
                out.push_str("        type ipv4_addr\n");
                out.push_str("        size 65535\n");
                out.push_str("        flags dynamic,timeout\n");
                out.push_str("        timeout 1m\n");
                out.push_str("    }\n\n");
            }
        }
    }

    // 1a. Emit allowlist sets per gateway when configured
    for gw in config.gateways.values() {
        let has_allow_rules = !gw.allow.is_empty() || !config.global_allow.is_empty();
        if has_allow_rules {
            let gw_id = gw.nft_id();
            let elements = resolve_gateway_allow_set(gw, config, state);
            let raw_rules: Vec<&String> =
                config.global_allow.iter().chain(gw.allow.iter()).collect();
            out.push_str(&format!(
                "    # allow-list rules for gateway {}: {:?}\n",
                gw.key, raw_rules
            ));
            out.push_str(&format!("    set allow_gw_{} {{\n", gw_id));
            out.push_str("        type ipv4_addr\n");
            out.push_str("        flags interval\n");
            if !elements.is_empty() {
                out.push_str(&format!(
                    "        elements = {{ {} }}\n",
                    elements.join(", ")
                ));
            }
            out.push_str("    }\n\n");
        }
    }

    // 1b. Emit DNS-driven nftset dynamic routing/bypass sets if configured
    let mut dns_route_gws = BTreeSet::new();
    let mut dns_bypass_gws = BTreeSet::new();
    if let Some(dns) = &config.dns {
        for r in &dns.nft_rules {
            if let Some(gw) = config.gateways.get(&r.gateway) {
                match r.action {
                    DnsNftAction::Route => {
                        dns_route_gws.insert(gw.nft_id());
                    }
                    DnsNftAction::Bypass => {
                        dns_bypass_gws.insert(gw.nft_id());
                    }
                }
            }
        }
    }
    for gw_id in &dns_bypass_gws {
        out.push_str(&format!("    set dns_bypass_{} {{\n", gw_id));
        out.push_str("        type ipv4_addr\n");
        out.push_str("        size 65535\n");
        out.push_str("        flags dynamic,timeout\n");
        out.push_str("        timeout 1h\n");
        out.push_str("    }\n\n");
    }
    for gw_id in &dns_route_gws {
        out.push_str(&format!("    set dns_route_{} {{\n", gw_id));
        out.push_str("        type ipv4_addr\n");
        out.push_str("        size 65535\n");
        out.push_str("        flags dynamic,timeout\n");
        out.push_str("        timeout 1h\n");
        out.push_str("    }\n\n");
    }

    // 1c. If WireGuard Virtual Gateways have tunnels configured, emit per-tunnel mark chains + mangle_prerouting ECMP vmap
    let any_wg_tunnels = config.gateways.values().any(|g| !g.tunnels.is_empty());
    let any_direct_gw = config.gateways.values().any(|g| g.tunnels.is_empty());
    if any_wg_tunnels {
        let mut global_idx = 0usize;
        for gw in config.gateways.values() {
            for t in &gw.tunnels {
                let chain_id = format!("mark_wg_{}", global_idx);
                let fwmark = 0x101 + global_idx;
                global_idx += 1;
                out.push_str(&format!("    chain {} {{\n", chain_id));
                out.push_str(&format!("        meta mark set 0x{:x}\n", fwmark));
                out.push_str("        ct mark set meta mark\n");
                out.push_str(&format!(
                    "        counter comment \"nfty:wg-mark={}\"\n",
                    t.endpoint_key()
                ));
                out.push_str("    }\n\n");
            }
        }

        out.push_str("    chain mangle_prerouting {\n");
        out.push_str("        type filter hook prerouting priority mangle; policy accept;\n");
        let mut inbound_wg_idx = 0usize;
        for gw in config.gateways.values() {
            for t in &gw.tunnels {
                let iface = if t.iface.is_empty() {
                    format!("wg{}", inbound_wg_idx)
                } else {
                    t.iface.clone()
                };
                let fwmark = 0x101 + inbound_wg_idx;
                inbound_wg_idx += 1;
                if !gw.forwards.is_empty() {
                    out.push_str(&format!(
                        "        iifname \"{}\" ct state new ct mark set 0x{:x} accept\n",
                        iface, fwmark
                    ));
                }
            }
        }
        out.push_str("        iifname \"wg*\" accept\n");
        out.push_str("        ip daddr { 10.0.0.0/8, 127.0.0.0/8, 169.254.0.0/16, 172.16.0.0/12, 224.0.0.0/4, 255.255.255.255 } accept\n");
        for gw_id in &dns_bypass_gws {
            out.push_str(&format!(
                "        ip daddr @dns_bypass_{} counter accept comment \"nfty:dns-bypass={}\"\n",
                gw_id, gw_id
            ));
        }
        out.push_str("        ct mark != 0x0 meta mark set ct mark accept\n");

        let wg_gw_count = config
            .gateways
            .values()
            .filter(|g| !g.tunnels.is_empty())
            .count();
        let mut base_idx = 0usize;
        for gw in config.gateways.values() {
            if gw.tunnels.is_empty() {
                continue;
            }
            let mut active_indices = Vec::new();
            for (local_i, t) in gw.tunnels.iter().enumerate() {
                let idx = base_idx + local_i;
                let healthy = state
                    .and_then(|st| st.runtime.get(&t.endpoint_key()))
                    .map(|rt| !rt.drained && rt.health != HealthState::Down)
                    .unwrap_or(true);
                if healthy {
                    for _ in 0..t.weight.max(1) {
                        active_indices.push(idx);
                    }
                }
            }
            if active_indices.is_empty() && !gw.tunnels.is_empty() {
                for local_i in 0..gw.tunnels.len() {
                    active_indices.push(base_idx + local_i);
                }
            }
            base_idx += gw.tunnels.len();

            let gw_id = gw.nft_id();
            let has_gw_allow = !gw.allow.is_empty() || !config.global_allow.is_empty();
            let gw_allow_prefix = if has_gw_allow {
                format!("ip saddr @allow_gw_{} ", gw_id)
            } else {
                String::new()
            };
            if dns_route_gws.contains(&gw_id) && !active_indices.is_empty() {
                out.push_str(&format!(
                    "        {}ip daddr @dns_route_{} jump mark_wg_{} accept\n",
                    gw_allow_prefix, gw_id, active_indices[0]
                ));
            }

            // When multiple tunnel gateways exist and this gateway has its own dedicated DHCP/VLAN interface,
            // scope the mangle rule to traffic arriving on that interface.
            let mut gw_scope_prefix = if wg_gw_count > 1 {
                if let Some(vip) = &gw.vip {
                    if vip.dhcp {
                        let mv = dhcp_macvlan_iface_name(&gw.key);
                        format!("iifname \"{}\" ", mv)
                    } else if vip.vlan.is_some() || vip.interface != "eth0" {
                        format!("iifname \"{}\" ", vip.effective_base_iface())
                    } else {
                        String::new()
                    }
                } else {
                    String::new()
                }
            } else {
                String::new()
            };
            gw_scope_prefix.push_str(&gw_allow_prefix);

            if active_indices.len() == 1 {
                out.push_str(&format!(
                    "        {}jump mark_wg_{}\n",
                    gw_scope_prefix, active_indices[0]
                ));
            } else if active_indices.len() > 1 {
                let total = active_indices.len();
                let selector = match gw.balance {
                    BalanceStrategy::RoundRobin => format!("numgen inc mod {}", total),
                    BalanceStrategy::Sticky => format!("jhash ip saddr . ip daddr mod {}", total),
                };
                let vmap_entries: Vec<String> = active_indices
                    .iter()
                    .enumerate()
                    .map(|(slot, idx)| format!("{} : jump mark_wg_{}", slot, idx))
                    .collect();
                out.push_str(&format!(
                    "        {}{} vmap {{ {} }}\n",
                    gw_scope_prefix,
                    selector,
                    vmap_entries.join(", ")
                ));
            }
        }
        out.push_str("    }\n\n");
    }

    // 2. Prerouting chain (VIP match, allowlist, DDoS rate-limit, DNAT load balancing)
    out.push_str("    chain prerouting {\n");
    out.push_str("        type nat hook prerouting priority dstnat; policy accept;\n");

    for svc in config.services.values() {
        if svc.vip_id.is_some() && svc.listen_ip.is_none() {
            out.push_str(&format!(
                "\n        # service {} (waiting for DHCP lease on vip {})\n",
                svc.key,
                svc.vip_id.as_deref().unwrap_or("?")
            ));
            continue;
        }
        let active_backends: Vec<&Backend> = match state {
            Some(st) => st.active_backends_for_service(&svc.backends),
            None => {
                let primaries: Vec<&Backend> = svc.backends.iter().filter(|b| !b.backup).collect();
                if primaries.is_empty() {
                    svc.backends.iter().collect()
                } else {
                    primaries
                }
            }
        };

        if active_backends.is_empty() {
            out.push_str(&format!(
                "\n        # service {} (no backends configured)\n",
                svc.key
            ));
            continue;
        }

        let has_allow_rules = !svc.allow.is_empty() || !config.global_allow.is_empty();
        let use_l7_vhost = (svc.port == 80 || svc.port == 443)
            && svc.hostname.is_some()
            && config
                .services
                .values()
                .filter(|other| {
                    other.listen_ip == svc.listen_ip
                        && (other.port == svc.port || other.hostname.is_some())
                })
                .count()
                > 1;
        out.push_str(&format!("\n        # --- service {} ---\n", svc.key));
        for proto_str in expand_protos(svc.proto) {
            emit_service_prerouting(
                &mut out,
                svc,
                proto_str,
                &active_backends,
                has_allow_rules,
                use_l7_vhost && proto_str == "tcp",
            );
        }
    }

    let mut gw_tunnel_offset = 0usize;
    for gw in config.gateways.values() {
        let tunnel_ifaces: Vec<String> = gw
            .tunnels
            .iter()
            .enumerate()
            .map(|(local_i, t)| {
                let idx = gw_tunnel_offset + local_i;
                if t.iface.is_empty() {
                    format!("\"wg{}\"", idx)
                } else {
                    format!("\"{}\"", t.iface)
                }
            })
            .collect();
        gw_tunnel_offset += gw.tunnels.len();

        let has_gw_allow = !gw.allow.is_empty() || !config.global_allow.is_empty();
        let gw_allow_guard = if has_gw_allow {
            format!(" ip saddr @allow_gw_{}", gw.nft_id())
        } else {
            String::new()
        };

        if !gw.listen_ip.is_unspecified() {
            for gs in &gw.services {
                match gs.kind {
                    GatewayServiceKind::Ssh => {
                        out.push_str(&format!(
                            "\n        # --- gateway {} service ssh:{} ---\n        ip daddr {} tcp dport {}{} counter redirect to :22 comment \"nfty:gw-ssh={}\"\n",
                            gw.key, gs.port, gw.listen_ip, gs.port, gw_allow_guard, gw.key
                        ));
                    }
                    GatewayServiceKind::Api | GatewayServiceKind::Web => {
                        out.push_str(&format!(
                            "\n        # --- gateway {} service {}:{} ---\n        ip daddr {} tcp dport {}{} counter redirect to :{} comment \"nfty:gw-api={}\"\n",
                            gw.key, gs.kind, gs.port, gw.listen_ip, gs.port, gw_allow_guard, gs.port, gw.key
                        ));
                    }
                    GatewayServiceKind::Privoxy
                    | GatewayServiceKind::Socks5
                    | GatewayServiceKind::Dns => {}
                }
            }
        }

        if !gw.forwards.is_empty() {
            let iif_match = if tunnel_ifaces.len() == 1 {
                format!("iifname {}", tunnel_ifaces[0])
            } else if tunnel_ifaces.len() > 1 {
                format!("iifname {{ {} }}", tunnel_ifaces.join(", "))
            } else {
                "iifname \"wg*\"".to_string()
            };
            for fwd in &gw.forwards {
                if fwd.backend.ip.is_unspecified() {
                    out.push_str(&format!(
                        "\n        # gateway {} forward {} -> {} (waiting for DNS resolution)\n",
                        gw.key, fwd.listen_port, fwd.backend
                    ));
                    continue;
                }
                out.push_str(&format!(
                    "\n        # --- gateway {} forward {} -> {}:{} ---\n",
                    gw.key, fwd.listen_port, fwd.backend.ip, fwd.backend.port
                ));
                for proto_str in expand_protos(fwd.proto) {
                    out.push_str(&format!(
                        "        {} {} dport {}{} counter dnat to {}:{} comment \"nfty:gw-fwd={}:{}\"\n",
                        iif_match,
                        proto_str,
                        fwd.listen_port,
                        gw_allow_guard,
                        fwd.backend.ip,
                        fwd.backend.port,
                        gw.key,
                        fwd.listen_port
                    ));
                }
            }
        }
    }
    out.push_str("    }\n\n");

    // 2b. Input chain (restrict SSH and API on VIPs unless explicitly enabled via service <vip>:22 / api:<port> or gateway service)
    let mut ssh_allowed_vips = BTreeSet::new();
    let mut api_allowed_vips = BTreeSet::new();
    let mut all_vips = BTreeSet::new();
    for (k, v) in &config.vips {
        if let Ok(ip) = k.parse::<std::net::Ipv4Addr>() {
            if !ip.is_unspecified() {
                all_vips.insert(ip);
            }
        }
        if let Some(leased) = v.leased_ip {
            if !leased.is_unspecified() {
                all_vips.insert(leased);
            }
        }
    }
    for svc in config.services.values() {
        if let Some(ip) = svc.listen_ip {
            if !ip.is_unspecified() {
                all_vips.insert(ip);
                if svc.port == 22 && svc.backends.iter().any(|b| b.ip.is_loopback() && b.port == 22) {
                    ssh_allowed_vips.insert(ip);
                }
                if svc.is_local_api_or_web() && svc.port == 9090 {
                    api_allowed_vips.insert(ip);
                }
            }
        }
    }
    for gw in config.gateways.values() {
        if !gw.listen_ip.is_unspecified() {
            all_vips.insert(gw.listen_ip);
            if gw
                .services
                .iter()
                .any(|gs| gs.kind == GatewayServiceKind::Ssh && gs.port == 22)
            {
                ssh_allowed_vips.insert(gw.listen_ip);
            }
            if gw.services.iter().any(|gs| {
                matches!(gs.kind, GatewayServiceKind::Api | GatewayServiceKind::Web)
                    && gs.port == 9090
            }) {
                api_allowed_vips.insert(gw.listen_ip);
            }
        }
    }
    let ssh_blocked_vips: Vec<String> = all_vips
        .iter()
        .filter(|ip| !ssh_allowed_vips.contains(ip))
        .map(|ip| ip.to_string())
        .collect();
    let api_blocked_vips: Vec<String> = if config.has_any_api_service() {
        all_vips
            .iter()
            .filter(|ip| !api_allowed_vips.contains(ip))
            .map(|ip| ip.to_string())
            .collect()
    } else {
        Vec::new()
    };
    if !ssh_blocked_vips.is_empty() || !api_blocked_vips.is_empty() {
        out.push_str("    chain input {\n");
        out.push_str("        type filter hook input priority filter; policy accept;\n");
        if !ssh_blocked_vips.is_empty() {
            out.push_str(&format!(
                "        ip daddr {{ {} }} tcp dport 22 counter drop comment \"nfty:ssh-disabled-on-vip\"\n",
                ssh_blocked_vips.join(", ")
            ));
        }
        if !api_blocked_vips.is_empty() {
            out.push_str(&format!(
                "        ip daddr {{ {} }} tcp dport 9090 counter drop comment \"nfty:api-disabled-on-vip\"\n",
                api_blocked_vips.join(", ")
            ));
        }
        out.push_str("    }\n\n");
    }

    // 3. Forward chain (per-backend traffic accounting counters & accept for DNAT'd traffic)
    out.push_str("    chain forward {\n");
    out.push_str("        type filter hook forward priority filter; policy accept;\n");
    out.push_str("        ct state established,related accept\n");

    for svc in config.services.values() {
        for proto_str in expand_protos(svc.proto) {
            for b in &svc.backends {
                out.push_str(&format!(
                    "        ip daddr {} {} dport {} counter accept comment \"nfty:backend={}\"\n",
                    b.ip,
                    proto_str,
                    b.port,
                    b.endpoint()
                ));
            }
        }
    }
    for gw in config.gateways.values() {
        for fwd in &gw.forwards {
            if !fwd.backend.ip.is_unspecified() {
                for proto_str in expand_protos(fwd.proto) {
                    out.push_str(&format!(
                        "        ip daddr {} {} dport {} counter accept comment \"nfty:backend={}\"\n",
                        fwd.backend.ip,
                        proto_str,
                        fwd.backend.port,
                        fwd.backend.endpoint()
                    ));
                }
            }
        }
    }
    if any_wg_tunnels {
        out.push_str("        oifname \"wg*\" counter accept comment \"nfty:wg-forward\"\n");
        out.push_str("        iifname \"wg*\" ct state established,related counter accept\n");
        let any_killswitch = config.gateways.values().any(|g| !g.tunnels.is_empty() && g.killswitch);
        if any_killswitch {
            out.push_str("        oifname \"eth0\" ip daddr != { 10.0.0.0/8, 127.0.0.0/8, 169.254.0.0/16, 172.16.0.0/12, 224.0.0.0/4 } meta mark != 0x0 counter drop comment \"nfty:killswitch\"\n");
        }
    }
    if any_direct_gw {
        out.push_str("        oifname \"eth0\" counter accept comment \"nfty:direct-gw-forward\"\n");
    }
    out.push_str("        ct status dnat accept\n");
    out.push_str("    }\n\n");

    // 4. Postrouting chain (Mode NAT vs Mode Transparent + Gateway Masquerade)
    out.push_str("    chain postrouting {\n");
    out.push_str("        type nat hook postrouting priority srcnat; policy accept;\n");
    if any_wg_tunnels {
        let mut global_idx = 0usize;
        for gw in config.gateways.values() {
            for t in &gw.tunnels {
                let iface = if t.iface.is_empty() {
                    format!("wg{}", global_idx)
                } else {
                    t.iface.clone()
                };
                global_idx += 1;
                out.push_str(&format!(
                    "        oifname \"{}\" counter masquerade comment \"nfty:backend={}\"\n",
                    iface,
                    t.endpoint_key()
                ));
            }
        }
        out.push_str("        oifname \"wg*\" counter masquerade comment \"nfty:wg-nat\"\n");
    }
    if any_direct_gw {
        out.push_str("        oifname \"eth0\" ip saddr != 127.0.0.0/8 ip daddr != { 10.0.0.0/8, 127.0.0.0/8, 169.254.0.0/16, 172.16.0.0/12, 224.0.0.0/4 } counter masquerade comment \"nfty:direct-gw-nat\"\n");
    }
    for gw_id in &dns_bypass_gws {
        out.push_str(&format!(
            "        oifname \"eth0\" ip saddr != 127.0.0.0/8 ip daddr @dns_bypass_{} counter masquerade comment \"nfty:dns-bypass-nat\"\n",
            gw_id
        ));
    }
    for svc in config.services.values() {
        match svc.mode {
            ForwardMode::Nat => {
                for proto_str in expand_protos(svc.proto) {
                    for b in &svc.backends {
                        if !b.ip.is_loopback() {
                            out.push_str(&format!(
                                "        ip daddr {} {} dport {} ct status dnat masquerade comment \"nfty:nat:svc={}\"\n",
                                b.ip, proto_str, b.port, svc.key
                            ));
                        }
                    }
                }
            }
            ForwardMode::Transparent => {
                out.push_str(&format!(
                    "        # service {} uses mode transparent (client source IP preserved)\n",
                    svc.key
                ));
            }
        }
    }
    out.push_str("    }\n");
    out.push_str("}\n");

    out
}

fn expand_protos(proto: Proto) -> Vec<&'static str> {
    match proto {
        Proto::Tcp => vec!["tcp"],
        Proto::Udp => vec!["udp"],
        Proto::Both => vec!["tcp", "udp"],
    }
}

fn emit_service_prerouting(
    out: &mut String,
    svc: &Service,
    proto_str: &str,
    active_backends: &[&Backend],
    has_allow_rules: bool,
    use_l7_vhost: bool,
) {
    let id = svc.nft_id();
    let mut match_prefix = String::new();
    if let Some(lip) = svc.listen_ip {
        match_prefix.push_str(&format!("ip daddr {} ", lip));
    }
    match_prefix.push_str(&format!("{} dport {}", proto_str, svc.port));

    let mut allow_guard = String::new();
    if has_allow_rules {
        allow_guard = format!(" ip saddr @allow_{}", id);
    }

    let mut rate_guard = String::new();
    if let Some(limit) = &svc.limit {
        let burst_part = limit
            .burst
            .map(|b| format!(" burst {} packets", b))
            .unwrap_or_else(|| format!(" burst {} packets", (limit.rate / 2).max(5)));
        if limit.per_ip {
            rate_guard = format!(
                " update @meter_{} {{ ip saddr limit rate {}/{}{} }}",
                id,
                limit.rate,
                limit.unit.to_nft_unit(),
                burst_part
            );
        } else {
            rate_guard = format!(
                " limit rate {}/{}{}",
                limit.rate,
                limit.unit.to_nft_unit(),
                burst_part
            );
        }
    }

    if use_l7_vhost {
        out.push_str(&format!(
            "        {}{}{} counter redirect to :{} comment \"nfty:svc={}\"\n",
            match_prefix, allow_guard, rate_guard, svc.port, svc.key
        ));
        return;
    }

    let mut slots: Vec<&Backend> = Vec::new();
    for b in active_backends {
        for _ in 0..b.weight.max(1) {
            slots.push(b);
        }
    }

    if slots.len() == 1 {
        let b = slots[0];
        if b.ip.is_loopback() {
            let redirect_port = if svc.is_local_api_or_web() {
                svc.port
            } else {
                b.port
            };
            out.push_str(&format!(
                "        {}{}{} counter redirect to :{} comment \"nfty:svc={}\"\n",
                match_prefix, allow_guard, rate_guard, redirect_port, svc.key
            ));
        } else {
            out.push_str(&format!(
                "        {}{}{} counter dnat to {}:{} comment \"nfty:svc={}\"\n",
                match_prefix, allow_guard, rate_guard, b.ip, b.port, svc.key
            ));
        }
    } else {
        let total = slots.len();
        let selector = match svc.balance {
            BalanceStrategy::RoundRobin => format!("numgen inc mod {}", total),
            BalanceStrategy::Sticky => format!("jhash ip saddr mod {}", total),
        };
        let mut map_entries = Vec::new();
        for (idx, b) in slots.iter().enumerate() {
            map_entries.push(format!("{} : {}", idx, b.ip));
        }

        let first_port = slots[0].port;
        let same_port = slots.iter().all(|b| b.port == first_port);
        if same_port {
            out.push_str(&format!(
                "        {}{}{} counter dnat to {} map {{ {} }}:{} comment \"nfty:svc={}\"\n",
                match_prefix,
                allow_guard,
                rate_guard,
                selector,
                map_entries.join(", "),
                first_port,
                svc.key
            ));
        } else {
            let mut full_entries = Vec::new();
            for (idx, b) in slots.iter().enumerate() {
                full_entries.push(format!("{} : {} . {}", idx, b.ip, b.port));
            }
            out.push_str(&format!(
                "        {}{}{} counter dnat ip to {} map {{ {} }} comment \"nfty:svc={}\"\n",
                match_prefix,
                allow_guard,
                rate_guard,
                selector,
                full_entries.join(", "),
                svc.key
            ));
        }
    }
}

pub fn dhcp_macvlan_iface_name(vip_key: &str) -> String {
    let clean: String = vip_key
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '-')
        .map(|c| c.to_ascii_lowercase())
        .collect();
    if clean.len() <= 11 && !clean.is_empty() {
        format!("mv-{}", clean)
    } else {
        let mut h: u32 = 2166136261;
        for b in vip_key.as_bytes() {
            h ^= *b as u32;
            h = h.wrapping_mul(16777619);
        }
        let prefix: String = clean.chars().take(6).collect();
        format!("mv-{}-{:04x}", prefix, h & 0xffff)
    }
}

pub fn dhcp_macvlan_mac(vip_key: &str) -> String {
    let mut h: u32 = 2166136261;
    for b in vip_key.as_bytes() {
        h ^= *b as u32;
        h = h.wrapping_mul(16777619);
    }
    format!(
        "02:6e:66:{:02x}:{:02x}:{:02x}",
        (h >> 16) & 0xff,
        (h >> 8) & 0xff,
        h & 0xff
    )
}

fn ensure_vlan_interface(vip: &crate::ast::VipConfig, logs: &mut Vec<String>) {
    let (parent_dev, vlan_id, vlan_iface) = if let Some(vid) = vip.vlan {
        let suffix = format!(".{}", vid);
        let parent = vip.interface.strip_suffix(&suffix).unwrap_or(&vip.interface);
        (parent.to_string(), vid, format!("{}.{}", parent, vid))
    } else if let Some((left, right)) = vip.interface.rsplit_once('.') {
        if let Ok(vid) = right.parse::<u16>() {
            if (1..=4094).contains(&vid) {
                (left.to_string(), vid, vip.interface.clone())
            } else {
                return;
            }
        } else {
            return;
        }
    } else {
        return;
    };

    let sys_path = format!("/sys/class/net/{}", vlan_iface);
    if !std::path::Path::new(&sys_path).exists() {
        let vid_str = vlan_id.to_string();
        if let Ok(out) = Command::new("ip")
            .args([
                "link",
                "add",
                "link",
                &parent_dev,
                "name",
                &vlan_iface,
                "type",
                "vlan",
                "id",
                &vid_str,
            ])
            .output()
        {
            if out.status.success() {
                logs.push(format!(
                    "VLAN created: {} (802.1Q tag {} on {})",
                    vlan_iface, vlan_id, parent_dev
                ));
            }
        }
    }
    let _ = Command::new("ip")
        .args(["link", "set", "dev", &vlan_iface, "up"])
        .status();
}

pub fn reconcile_dhcp_and_vlan_vips(cfg: &mut Config) -> Vec<String> {
    let mut logs = Vec::new();
    if unsafe { libc::geteuid() != 0 } {
        return logs;
    }

    // 1. Ensure 802.1Q VLAN interfaces exist for all VIPs, services, and gateways
    let mut all_vip_cfgs = Vec::new();
    for v in cfg.vips.values() {
        all_vip_cfgs.push(v.clone());
    }
    for s in cfg.services.values() {
        if let Some(v) = &s.vip {
            all_vip_cfgs.push(v.clone());
        }
    }
    for g in cfg.gateways.values() {
        if let Some(v) = &g.vip {
            all_vip_cfgs.push(v.clone());
        }
    }
    for v in &all_vip_cfgs {
        ensure_vlan_interface(v, &mut logs);
    }

    // 2. Reconcile DHCP VIP macvlan interfaces + udhcpc leases
    let mut active_mv_ifaces = BTreeSet::new();
    let vip_keys: Vec<String> = cfg.vips.keys().cloned().collect();
    for vip_key in vip_keys {
        let Some(vip_cfg) = cfg.vips.get(&vip_key).cloned() else {
            continue;
        };
        if !vip_cfg.dhcp {
            continue;
        }
        let mv_iface = dhcp_macvlan_iface_name(&vip_key);
        active_mv_ifaces.insert(mv_iface.clone());
        let mac = dhcp_macvlan_mac(&vip_key);
        let parent_iface = vip_cfg.effective_base_iface();

        let mv_sys = format!("/sys/class/net/{}", mv_iface);
        let lower_sys = format!("/sys/class/net/{}/lower_{}", mv_iface, parent_iface);
        if std::path::Path::new(&mv_sys).exists() && !std::path::Path::new(&lower_sys).exists() {
            // Parent interface changed (e.g. VLAN changed); recreate macvlan
            let _ = Command::new("ip")
                .args(["link", "del", "dev", &mv_iface])
                .status();
        }

        if !std::path::Path::new(&mv_sys).exists() {
            let _ = Command::new("ip")
                .args([
                    "link",
                    "add",
                    "link",
                    &parent_iface,
                    "name",
                    &mv_iface,
                    "address",
                    &mac,
                    "type",
                    "macvlan",
                    "mode",
                    "bridge",
                ])
                .status();
            let _ = Command::new("ip")
                .args(["link", "set", "dev", &mv_iface, "up"])
                .status();
        } else {
            let _ = Command::new("ip")
                .args(["link", "set", "dev", &mv_iface, "up"])
                .status();
        }

        // Prevent ARP flux on macvlan
        let _ = std::fs::write("/proc/sys/net/ipv4/conf/all/arp_ignore", "1\n");
        let _ = std::fs::write("/proc/sys/net/ipv4/conf/all/arp_announce", "2\n");
        let _ = std::fs::write("/proc/sys/net/ipv4/conf/all/rp_filter", "0\n");
        let _ = std::fs::write(format!("/proc/sys/net/ipv4/conf/{}/arp_ignore", mv_iface), "1\n");
        let _ = std::fs::write(
            format!("/proc/sys/net/ipv4/conf/{}/arp_announce", mv_iface),
            "2\n",
        );
        let _ = std::fs::write(format!("/proc/sys/net/ipv4/conf/{}/rp_filter", mv_iface), "0\n");

        let pid_file = format!("/run/udhcpc-{}.pid", mv_iface);
        let ip_file = format!("/run/nfty-dhcp-{}.ip", mv_iface);
        let udhcpc_running = std::fs::read_to_string(&pid_file)
            .ok()
            .and_then(|s| s.trim().parse::<u32>().ok())
            .map(|pid| std::path::Path::new(&format!("/proc/{}", pid)).exists())
            .unwrap_or(false);

        if !udhcpc_running || !std::path::Path::new(&ip_file).exists() {
            if let Ok(old_pid_str) = std::fs::read_to_string(&pid_file) {
                if let Ok(old_pid) = old_pid_str.trim().parse::<i32>() {
                    unsafe {
                        libc::kill(old_pid, libc::SIGTERM);
                    }
                }
            }
            let hostname: String = vip_key
                .chars()
                .filter(|c| c.is_ascii_alphanumeric() || *c == '-')
                .collect();
            let host_opt = format!("hostname:{}", if hostname.is_empty() { "nfty-vip" } else { &hostname });
            let udhcpc_bin = if std::path::Path::new("/sbin/udhcpc").exists() {
                "/sbin/udhcpc"
            } else {
                "udhcpc"
            };
            let _ = Command::new(udhcpc_bin)
                .args([
                    "-i",
                    &mv_iface,
                    "-x",
                    &host_opt,
                    "-p",
                    &pid_file,
                    "-s",
                    "/bin/udhcpc-hook",
                    "-t",
                    "3",
                    "-T",
                    "1",
                    "-A",
                    "60",
                    "-b",
                ])
                .status();
        }

        if let Ok(raw_ip) = std::fs::read_to_string(&ip_file) {
            if let Ok(leased_ip) = raw_ip.trim().parse::<std::net::Ipv4Addr>() {
                if let Some(v) = cfg.vips.get_mut(&vip_key) {
                    v.leased_ip = Some(leased_ip);
                }
                let updated_vip = cfg.vips.get(&vip_key).cloned();
                for svc in cfg.services.values_mut() {
                    if svc.belongs_to_vip(&vip_key) {
                        svc.listen_ip = Some(leased_ip);
                        svc.vip = updated_vip.clone();
                    }
                }
                logs.push(format!(
                    "DHCP VIP '{}' -> {} on {} (parent {}, MAC {})",
                    vip_key, leased_ip, mv_iface, parent_iface, mac
                ));
            }
        }
    }

    // 2b. Reconcile DHCP Gateway macvlan interfaces + udhcpc leases
    let gw_keys: Vec<String> = cfg.gateways.keys().cloned().collect();
    for gw_key in gw_keys {
        let Some(vip_cfg) = cfg.gateways.get(&gw_key).and_then(|g| g.vip.clone()) else {
            continue;
        };
        if !vip_cfg.dhcp {
            continue;
        }
        let mv_iface = dhcp_macvlan_iface_name(&gw_key);
        active_mv_ifaces.insert(mv_iface.clone());
        let mac = dhcp_macvlan_mac(&gw_key);
        let parent_iface = vip_cfg.effective_base_iface();

        let mv_sys = format!("/sys/class/net/{}", mv_iface);
        let lower_sys = format!("/sys/class/net/{}/lower_{}", mv_iface, parent_iface);
        if std::path::Path::new(&mv_sys).exists() && !std::path::Path::new(&lower_sys).exists() {
            let _ = Command::new("ip")
                .args(["link", "del", "dev", &mv_iface])
                .status();
        }

        if !std::path::Path::new(&mv_sys).exists() {
            let _ = Command::new("ip")
                .args([
                    "link",
                    "add",
                    "link",
                    &parent_iface,
                    "name",
                    &mv_iface,
                    "address",
                    &mac,
                    "type",
                    "macvlan",
                    "mode",
                    "bridge",
                ])
                .status();
        }
        let _ = Command::new("ip")
            .args(["link", "set", "dev", &mv_iface, "up"])
            .status();

        let _ = std::fs::write(format!("/proc/sys/net/ipv4/conf/{}/arp_ignore", mv_iface), "1\n");
        let _ = std::fs::write(
            format!("/proc/sys/net/ipv4/conf/{}/arp_announce", mv_iface),
            "2\n",
        );
        let _ = std::fs::write(format!("/proc/sys/net/ipv4/conf/{}/rp_filter", mv_iface), "0\n");

        let pid_file = format!("/run/udhcpc-{}.pid", mv_iface);
        let ip_file = format!("/run/nfty-dhcp-{}.ip", mv_iface);
        let udhcpc_running = std::fs::read_to_string(&pid_file)
            .ok()
            .and_then(|s| s.trim().parse::<u32>().ok())
            .map(|pid| std::path::Path::new(&format!("/proc/{}", pid)).exists())
            .unwrap_or(false);

        if !udhcpc_running || !std::path::Path::new(&ip_file).exists() {
            if let Ok(old_pid_str) = std::fs::read_to_string(&pid_file) {
                if let Ok(old_pid) = old_pid_str.trim().parse::<i32>() {
                    unsafe {
                        libc::kill(old_pid, libc::SIGTERM);
                    }
                }
            }
            let hostname: String = gw_key
                .chars()
                .filter(|c| c.is_ascii_alphanumeric() || *c == '-')
                .collect();
            let host_opt = format!(
                "hostname:{}",
                if hostname.is_empty() { "nfty-gw" } else { &hostname }
            );
            let udhcpc_bin = if std::path::Path::new("/sbin/udhcpc").exists() {
                "/sbin/udhcpc"
            } else {
                "udhcpc"
            };
            let _ = Command::new(udhcpc_bin)
                .args([
                    "-i",
                    &mv_iface,
                    "-x",
                    &host_opt,
                    "-p",
                    &pid_file,
                    "-s",
                    "/bin/udhcpc-hook",
                    "-t",
                    "3",
                    "-T",
                    "1",
                    "-A",
                    "60",
                    "-b",
                ])
                .status();
        }

        if let Ok(raw_ip) = std::fs::read_to_string(&ip_file) {
            if let Ok(leased_ip) = raw_ip.trim().parse::<std::net::Ipv4Addr>() {
                if let Some(gw) = cfg.gateways.get_mut(&gw_key) {
                    gw.listen_ip = leased_ip;
                    if let Some(v) = &mut gw.vip {
                        v.leased_ip = Some(leased_ip);
                    }
                }
                logs.push(format!(
                    "DHCP Gateway '{}' -> {} on {} (parent {}, MAC {})",
                    gw_key, leased_ip, mv_iface, parent_iface, mac
                ));
            }
        }
    }

    // 3. Clean up any stale mv-* interfaces no longer in cfg.vips or cfg.gateways
    if let Ok(entries) = std::fs::read_dir("/sys/class/net") {
        for entry in entries.flatten() {
            let name = entry.file_name().to_string_lossy().to_string();
            if name.starts_with("mv-") && !active_mv_ifaces.contains(&name) {
                let pid_file = format!("/run/udhcpc-{}.pid", name);
                let ip_file = format!("/run/nfty-dhcp-{}.ip", name);
                if let Ok(pid_str) = std::fs::read_to_string(&pid_file) {
                    if let Ok(pid) = pid_str.trim().parse::<i32>() {
                        unsafe {
                            libc::kill(pid, libc::SIGTERM);
                        }
                    }
                }
                let _ = std::fs::remove_file(&pid_file);
                let _ = std::fs::remove_file(&ip_file);
                let _ = Command::new("ip")
                    .args(["link", "del", "dev", &name])
                    .status();
                logs.push(format!("Removed DHCP VIP interface {}", name));
            }
        }
    }

    logs
}

pub fn generate_vip_commands(old_cfg: &Config, new_cfg: &Config) -> Vec<String> {
    let mut cmds = Vec::new();

    let collect_vips = |cfg: &Config| -> Vec<(std::net::Ipv4Addr, crate::ast::VipConfig)> {
        let mut list = Vec::new();
        for (ip_str, vip) in &cfg.vips {
            if vip.dhcp {
                continue;
            }
            if let Ok(ip) = ip_str.parse::<std::net::Ipv4Addr>() {
                if !list.iter().any(|(i, _)| *i == ip) {
                    list.push((ip, vip.clone()));
                }
            }
        }
        for svc in cfg.services.values() {
            if let (Some(ip), Some(vip)) = (svc.listen_ip, &svc.vip) {
                if vip.dhcp {
                    continue;
                }
                if !list.iter().any(|(i, _)| *i == ip) {
                    list.push((ip, vip.clone()));
                }
            }
        }
        for gw in cfg.gateways.values() {
            if let Some(vip) = &gw.vip {
                if vip.dhcp || gw.listen_ip.is_unspecified() {
                    continue;
                }
                if !list.iter().any(|(i, _)| *i == gw.listen_ip) {
                    list.push((gw.listen_ip, vip.clone()));
                }
            }
        }
        list
    };

    let old_vips = collect_vips(old_cfg);
    let new_vips = collect_vips(new_cfg);

    for (ip, vip) in &old_vips {
        let old_dev = vip.effective_base_iface();
        let still_present = new_vips.iter().any(|(new_ip, new_vip)| {
            new_ip == ip
                && new_vip.effective_base_iface() == old_dev
                && new_vip.prefix_len == vip.prefix_len
        });
        if !still_present {
            let cmd = format!(
                "ip addr del {}/{} dev {}",
                ip, vip.prefix_len, old_dev
            );
            if !cmds.contains(&cmd) {
                cmds.push(cmd);
            }
        }
    }

    for (ip, vip) in &new_vips {
        let new_dev = vip.effective_base_iface();
        let cmd = format!(
            "ip addr replace {}/{} dev {}",
            ip, vip.prefix_len, new_dev
        );
        if !cmds.contains(&cmd) {
            cmds.push(cmd);
        }
    }

    cmds
}

#[derive(Debug, serde::Serialize)]
pub struct ValidationReport {
    pub valid: bool,
    pub warnings: Vec<String>,
    pub errors: Vec<String>,
    pub nft_checked_with_kernel: bool,
    pub nft_message: String,
}

pub fn validate_config(config: &Config, state: Option<&AppState>) -> ValidationReport {
    let mut warnings = Vec::new();
    let mut errors = Vec::new();

    if config.vips.is_empty() && config.services.is_empty() && config.gateways.is_empty() {
        warnings.push("No VIPs, services, or gateways are defined in configuration.".to_string());
    }

    for svc in config.services.values() {
        if svc.backends.is_empty() {
            errors.push(format!(
                "service '{}': has no backend targets configured (use 'to <ip:port>')",
                svc.key
            ));
        }
        if let Some(vip) = &svc.vip {
            if !vip.dhcp && svc.listen_ip.is_none() && svc.vip_id.is_none() {
                errors.push(format!(
                    "service '{}': specifies 'vip {}' but service has no listen IP (use e.g. 'service 169.254.1.240:{}')",
                    svc.key,
                    vip,
                    svc.port
                ));
            }
        }
        if svc.backends.iter().all(|b| b.backup) && !svc.backends.is_empty() {
            warnings.push(format!(
                "service '{}': all backends are marked 'backup' (no primary backend defined)",
                svc.key
            ));
        }
    }

    let wg_gws: Vec<&Gateway> = config
        .gateways
        .values()
        .filter(|g| !g.tunnels.is_empty())
        .collect();
    if wg_gws.len() > 1 {
        let unscoped: Vec<&str> = wg_gws
            .iter()
            .filter(|g| {
                g.vip
                    .as_ref()
                    .map(|v| !v.dhcp && v.vlan.is_none() && v.interface == "eth0")
                    .unwrap_or(true)
            })
            .map(|g| g.key.as_str())
            .collect();
        if unscoped.len() > 1 {
            warnings.push(format!(
                "multiple WireGuard gateways ({}) share eth0 without dedicated DHCP macvlan or VLAN scoping; the first unscoped gateway in mangle_prerouting will match all unscoped traffic unless 'allow' rules or VLAN/DHCP interfaces distinguish them",
                unscoped.join(", ")
            ));
        }
    }

    let ruleset = compile_nft_ruleset(config, state);
    let (nft_checked_with_kernel, nft_ok, nft_message) = run_nft_command(&ruleset, true);
    if !nft_ok {
        errors.push(format!("nftables check failed: {}", nft_message));
    }

    ValidationReport {
        valid: errors.is_empty(),
        warnings,
        errors,
        nft_checked_with_kernel,
        nft_message,
    }
}

pub fn run_nft_command(ruleset: &str, check_only: bool) -> (bool, bool, String) {
    let mut cmd = Command::new("nft");
    if check_only {
        cmd.arg("-c");
    }
    cmd.arg("-f").arg("-");
    cmd.stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());

    match cmd.spawn() {
        Ok(mut child) => {
            if let Some(mut stdin) = child.stdin.take() {
                let _ = stdin.write_all(ruleset.as_bytes());
            }
            match child.wait_with_output() {
                Ok(output) => {
                    let stderr = String::from_utf8_lossy(&output.stderr).trim().to_string();
                    if output.status.success() {
                        (
                            true,
                            true,
                            if check_only {
                                "Kernel nftables syntax & netlink dry-run passed".to_string()
                            } else {
                                "Applied ruleset to kernel nftables".to_string()
                            },
                        )
                    } else if stderr.contains("Operation not permitted")
                        || stderr.contains("Permission denied")
                        || stderr.contains("must be root")
                    {
                        (
                            false,
                            true,
                            "Syntax verified (note: not running as root, kernel netlink simulated)"
                                .to_string(),
                        )
                    } else {
                        (true, false, stderr)
                    }
                }
                Err(e) => (false, true, format!("nft wait failed: {}", e)),
            }
        }
        Err(_) => (
            false,
            true,
            "AST & compiler verification passed (nft binary not in PATH; running in userspace/unikernel mode)"
                .to_string(),
        ),
    }
}

pub fn apply_vip_commands(cmds: &[String]) -> Vec<String> {
    let mut logs = Vec::new();
    for cmd_str in cmds {
        let parts: Vec<&str> = cmd_str.split_whitespace().collect();
        if parts.is_empty() {
            continue;
        }
        match Command::new(parts[0]).args(&parts[1..]).output() {
            Ok(out) if out.status.success() => {
                // If this was `ip addr replace <ip>/<prefix> dev <iface>`, send a Gratuitous ARP
                // so the upstream router/switch (UDM Pro) immediately updates its ARP cache!
                if parts.len() >= 6 && parts[1] == "addr" && parts[2] == "replace" {
                    let ip_only = parts[3].split('/').next().unwrap_or(parts[3]).to_string();
                    let iface = parts[5].to_string();
                    std::thread::spawn(move || {
                        let _ = Command::new("/bin/busybox")
                            .args(["arping", "-U", "-c", "2", "-w", "1", "-I", &iface, &ip_only])
                            .output();
                    });
                }
                logs.push(format!("VIP applied: {}", cmd_str));
            }
            Ok(out) => {
                let err = String::from_utf8_lossy(&out.stderr).trim().to_string();
                logs.push(format!("VIP command '{}' (non-root/staged): {}", cmd_str, err));
            }
            Err(_) => {
                logs.push(format!("VIP staged: {}", cmd_str));
            }
        }
    }
    logs
}

pub fn reload_kernel_from_state(state: &mut AppState) -> Result<String> {
    let _dhcp_logs = reconcile_dhcp_and_vlan_vips(&mut state.running);
    // Sync leased DHCP VIP IPs into candidate config as well so `status` and `show` stay in sync
    for (k, run_vip) in &state.running.vips {
        if let Some(leased) = run_vip.leased_ip {
            if let Some(cand_vip) = state.candidate.vips.get_mut(k) {
                cand_vip.leased_ip = Some(leased);
            }
            for svc in state.candidate.services.values_mut() {
                if svc.belongs_to_vip(k) {
                    svc.listen_ip = Some(leased);
                    if let Some(cv) = &mut svc.vip {
                        cv.leased_ip = Some(leased);
                    }
                }
            }
        }
    }
    for (k, run_gw) in &state.running.gateways {
        if let Some(leased) = run_gw.vip.as_ref().and_then(|v| v.leased_ip) {
            if let Some(cand_gw) = state.candidate.gateways.get_mut(k) {
                cand_gw.listen_ip = leased;
                if let Some(cv) = &mut cand_gw.vip {
                    cv.leased_ip = Some(leased);
                }
            }
        }
    }
    let _ = crate::features::apply_wireguard_gateways(&state.running);
    if unsafe { libc::geteuid() == 0 } {
        let cf_cfg = state.running.clone();
        std::thread::spawn(move || {
            let _ = crate::features::reconcile_cloudflare_tunnel(&cf_cfg);
        });
    }
    let ruleset = compile_nft_ruleset(&state.running, Some(state));
    let (in_kernel, ok, msg) = run_nft_command(&ruleset, false);
    if !ok {
        bail!("Failed to apply nftables ruleset: {}", msg);
    }
    state.last_applied_nft = ruleset;
    state.kernel_applied = in_kernel;
    if unsafe { libc::geteuid() == 0 } {
        let _ = crate::features::reconcile_dnsmasq(&state.running, Some(state));
    }
    Ok(msg)
}
