pub const DNSMASQ_CONF_PATH: &str = "/run/nfty-dnsmasq.conf";
pub const DNSMASQ_HOSTS_PATH: &str = "/run/nfty-dnsmasq.hosts";
pub const DNSMASQ_PID_PATH: &str = "/run/nfty-dnsmasq.pid";
pub const DNS_LISTS_DIR: &str = "/data/dns/lists";

fn find_gateway<'a>(cfg: &'a Config, gw_name_or_ip: &str) -> Option<&'a crate::ast::Gateway> {
    cfg.gateways.get(gw_name_or_ip).or_else(|| {
        cfg.gateways.values().find(|g| {
            g.key.eq_ignore_ascii_case(gw_name_or_ip)
                || g.listen_ip.to_string() == gw_name_or_ip
                || g.hostname.as_deref() == Some(gw_name_or_ip)
        })
    })
}

fn find_healthy_wg_iface_for_gateway(
    cfg: &Config,
    st: Option<&AppState>,
    gw_name_or_ip: &str,
) -> Option<String> {
    let gw = find_gateway(cfg, gw_name_or_ip)?;
    let base_idx = cfg.gateways.values().take_while(|g| g.key != gw.key)
        .map(|g| g.tunnels.len()).sum::<usize>();
    for (idx, t) in gw.tunnels.iter().enumerate() {
        let iface = if t.iface.is_empty() {
            format!("wg{}", base_idx + idx)
        } else {
            t.iface.clone()
        };
        let healthy = st
            .and_then(|s| s.runtime.get(&t.endpoint_key()))
            .map(|rt| !rt.drained && rt.health != HealthState::Down)
            .unwrap_or(true);
        if healthy {
            return Some(iface);
        }
    }
    None
}

fn service_is_healthy_for_dns(
    svc: &crate::ast::Service,
    st: Option<&AppState>,
) -> bool {
    if svc.backends.is_empty() {
        return svc.is_local_dns();
    }
    let Some(s) = st else {
        return true;
    };
    svc.backends.iter().any(|b| {
        s.runtime
            .get(&b.endpoint())
            .map(|rt| !rt.drained && rt.health != HealthState::Down)
            .unwrap_or(true)
    })
}

/// Compiles `Config` and runtime `AppState` into `(dnsmasq.conf, dnsmasq.hosts)`.
pub fn compile_dnsmasq_config(cfg: &Config, st: Option<&AppState>) -> (String, String) {
    let dns_cfg = cfg.dns.clone().unwrap_or_default();
    let mut conf = String::new();
    conf.push_str("# Generated by nfty — Programmable dnsmasq Configuration\n");
    conf.push_str("user=root\n");
    conf.push_str("group=root\n");
    conf.push_str("no-resolv\n");
    conf.push_str("no-poll\n");
    conf.push_str(&format!("addn-hosts={}\n", DNSMASQ_HOSTS_PATH));
    conf.push_str(&format!("pid-file={}\n", DNSMASQ_PID_PATH));
    conf.push_str(&format!("cache-size={}\n", dns_cfg.cache_size));
    conf.push_str("localise-queries\n");
    if !dns_cfg.auto_hosts {
        conf.push_str("no-hosts\n");
    }

    if dns_cfg.all_servers {
        conf.push_str("all-servers\n");
    }
    if dns_cfg.bogus_priv {
        conf.push_str("bogus-priv\n");
    }
    if dns_cfg.domain_needed {
        conf.push_str("domain-needed\n");
    }
    if let Some(dom) = &dns_cfg.domain {
        if !dom.is_empty() {
            conf.push_str("expand-hosts\n");
            conf.push_str(&format!("domain={}\n", dom));
            conf.push_str(&format!("local=/{}/\n", dom));
        }
    }

    // Determine listen addresses if explicitly scoped via `listen`, `vip { dns:53 }`, or `gateway { dns:53 }`
    let wildcard_listen = dns_cfg
        .listen
        .iter()
        .any(|l| l == "0.0.0.0" || l == "0.0.0.0:53" || l == "*");
    let mut addrs = BTreeSet::new();
    for l in &dns_cfg.listen {
        let ip_part = l.split(':').next().unwrap_or(l);
        if !ip_part.is_empty() && ip_part != "0.0.0.0" && ip_part != "*" {
            addrs.insert(ip_part.to_string());
        }
    }
    for svc in cfg.services.values().filter(|s| s.is_local_dns()) {
        if let Some(ip) = svc.listen_ip {
            if !ip.is_unspecified() {
                addrs.insert(ip.to_string());
            }
        }
    }
    for gw in cfg.gateways.values() {
        if gw.services.iter().any(|gs| gs.kind == GatewayServiceKind::Dns)
            && !gw.listen_ip.is_unspecified()
        {
            addrs.insert(gw.listen_ip.to_string());
        }
    }
    if !addrs.is_empty() && !wildcard_listen {
        addrs.insert("127.0.0.1".to_string());
        conf.push_str("bind-dynamic\n");
        for a in addrs {
            conf.push_str(&format!("listen-address={}\n", a));
        }
    }

    // Default gateway interface if a WireGuard gateway exposes dns:53 and upstreams don't specify @iface
    let default_wg_gateway = cfg
        .gateways
        .values()
        .find(|gw| {
            !gw.tunnels.is_empty()
                && gw.services.iter().any(|gs| gs.kind == GatewayServiceKind::Dns)
        });
    let default_wg_iface = default_wg_gateway
        .and_then(|gw| find_healthy_wg_iface_for_gateway(cfg, st, &gw.key));

    for u in &dns_cfg.upstreams {
        let formatted = if let Some((srv, target)) = u.split_once('@') {
            if let Some(wg_if) = find_healthy_wg_iface_for_gateway(cfg, st, target) {
                format!("{}@{}", srv.replace(':', "#"), wg_if)
            } else if find_gateway(cfg, target).is_some() {
                conf.push_str(&format!("# upstream {} blocked: gateway has no healthy tunnel\n", u));
                continue;
            } else {
                format!("{}@{}", srv.replace(':', "#"), target)
            }
        } else if let Some(wg_if) = &default_wg_iface {
            format!("{}@{}", u.replace(':', "#"), wg_if)
        } else if default_wg_gateway.is_some() {
            conf.push_str(&format!("# upstream {} blocked: gateway has no healthy tunnel\n", u));
            continue;
        } else {
            u.replace(':', "#")
        };
        conf.push_str(&format!("server={}\n", formatted));
    }

    // Conditional forward zones
    for fz in &dns_cfg.forward_zones {
        let dom = fz.domain.trim_start_matches("*.").trim_start_matches('.');
        let suffix = match &fz.via_gateway {
            Some(gw) => match find_healthy_wg_iface_for_gateway(cfg, st, gw) {
                Some(iface) => format!("@{}", iface),
                None => {
                    conf.push_str(&format!("local=/{}/\n", dom));
                    conf.push_str(&format!("# forward zone {} blocked: gateway has no healthy tunnel\n", dom));
                    continue;
                }
            },
            None => String::new(),
        };
        for srv in &fz.servers {
            let srv_clean = srv.replace(':', "#");
            conf.push_str(&format!("server=/{}/{}{}\n", dom, srv_clean, suffix));
        }
    }

    // Explicit DNS records
    for rec in &dns_cfg.records {
        match rec {
            DnsRecord::A { name, ips } => {
                for ip in ips {
                    if !name.contains('.') {
                        if let Some(dom) = &dns_cfg.domain {
                            conf.push_str(&format!("host-record={}.{},{},{}\n", name, dom, name, ip));
                            continue;
                        }
                    }
                    conf.push_str(&format!("host-record={},{}\n", name, ip));
                }
            }
            DnsRecord::Aaaa { name, ip } => {
                conf.push_str(&format!("host-record={},{}\n", name, ip));
            }
            DnsRecord::Address { domain, ip } => {
                let d = domain.trim_start_matches("*.").trim_start_matches('.');
                conf.push_str(&format!("address=/{}/{}\n", d, ip));
            }
            DnsRecord::Cname { alias, target } => {
                conf.push_str(&format!("cname={},{}\n", alias, target));
            }
            DnsRecord::Txt { name, text } => {
                conf.push_str(&format!("txt-record={},\"{}\"\n", name, text));
            }
            DnsRecord::Srv {
                service,
                target,
                port,
                priority,
                weight,
            } => {
                conf.push_str(&format!(
                    "srv-host={},{},{},{},{}\n",
                    service, target, port, priority, weight
                ));
            }
            DnsRecord::Mx {
                domain,
                target,
                preference,
            } => {
                conf.push_str(&format!("mx-host={},{},{}\n", domain, target, preference));
            }
            DnsRecord::Ptr { ip, name } => {
                let octets = ip.octets();
                conf.push_str(&format!(
                    "ptr-record={}.{}.{}.{}.in-addr.arpa,{}\n",
                    octets[3], octets[2], octets[1], octets[0], name
                ));
            }
        }
    }

    // DNS-to-nftables dynamic set population
    for nr in &dns_cfg.nft_rules {
        if let Some(gw) = cfg.gateways.get(&nr.gateway).or_else(|| {
            cfg.gateways
                .values()
                .find(|g| g.key.eq_ignore_ascii_case(&nr.gateway))
        }) {
            let set_name = match nr.action {
                DnsNftAction::Route => format!("dns_route_{}", gw.nft_id()),
                DnsNftAction::Bypass => format!("dns_bypass_{}", gw.nft_id()),
            };
            let doms: Vec<String> = nr
                .domains
                .iter()
                .map(|d| d.trim_start_matches("*.").trim_start_matches('.').to_string())
                .filter(|d| !d.is_empty())
                .collect();
            if !doms.is_empty() {
                conf.push_str(&format!(
                    "nftset=/{}/4#ip#nfty#{}\n",
                    doms.join("/"),
                    set_name
                ));
            }
        }
    }

    // Blocked domains & blocklists
    for b in &dns_cfg.blocks {
        let d = b.trim_start_matches("*.").trim_start_matches('.');
        if !d.is_empty() {
            conf.push_str(&format!("address=/{}/0.0.0.0\n", d));
            conf.push_str(&format!("address=/{}/::\n", d));
        }
    }
    for bl in &dns_cfg.blocklists {
        let list_file = format!("{}/{}.hosts", DNS_LISTS_DIR, bl.name);
        if Path::new(&list_file).exists() {
            conf.push_str(&format!("addn-hosts={}\n", list_file));
        }
    }

    for raw in &dns_cfg.raw_options {
        conf.push_str(&format!("{}\n", raw));
    }

    // Build /run/nfty-dnsmasq.hosts from auto_vips + auto_hosts
    let mut hosts_map: BTreeMap<Ipv4Addr, Vec<String>> = BTreeMap::new();
    let add_host_name = |map: &mut BTreeMap<Ipv4Addr, Vec<String>>, ip: Ipv4Addr, name: String| {
        if ip.is_unspecified() || ip.is_loopback() || name.is_empty() || name.contains('*') {
            return;
        }
        let list = map.entry(ip).or_default();
        if !list.iter().any(|x| x.eq_ignore_ascii_case(&name)) {
            list.push(name);
        }
    };

    if dns_cfg.auto_vips {
        for (vip_key, vip_cfg) in &cfg.vips {
            let ip_opt = vip_key.parse::<Ipv4Addr>().ok().or(vip_cfg.leased_ip);
            if let Some(ip) = ip_opt {
                if vip_key.parse::<Ipv4Addr>().is_err() {
                    add_host_name(&mut hosts_map, ip, vip_key.clone());
                    if !vip_key.contains('.') {
                        if let Some(dom) = &dns_cfg.domain {
                            add_host_name(&mut hosts_map, ip, format!("{}.{}", vip_key, dom));
                        }
                    }
                }
            }
        }

        for svc in cfg.services.values() {
            if dns_cfg.health_aware && !service_is_healthy_for_dns(svc, st) {
                continue;
            }
            let vip_ip = svc.listen_ip.or_else(|| {
                svc.vip_id
                    .as_ref()
                    .and_then(|vid| cfg.vips.get(vid))
                    .and_then(|v| v.leased_ip)
            });
            if let Some(ip) = vip_ip {
                if let Some(h) = &svc.hostname {
                    if let Some(bare) = h.strip_suffix(".local") {
                        add_host_name(&mut hosts_map, ip, bare.to_string());
                        if let Some(dom) = &dns_cfg.domain {
                            add_host_name(&mut hosts_map, ip, format!("{}.{}", bare, dom));
                        }
                    }
                    add_host_name(&mut hosts_map, ip, h.clone());
                }
                if let Some(cf) = &svc.cloudflare {
                    add_host_name(&mut hosts_map, ip, cf.clone());
                }
            }
        }

        for gw in cfg.gateways.values() {
            if !gw.listen_ip.is_unspecified() {
                if gw.key.parse::<Ipv4Addr>().is_err() {
                    add_host_name(&mut hosts_map, gw.listen_ip, gw.key.clone());
                }
                if let Some(h) = &gw.hostname {
                    add_host_name(&mut hosts_map, gw.listen_ip, h.clone());
                }
            }
        }
    }

    if dns_cfg.auto_hosts {
        let resolved = st.map(|s| s.resolved_hosts.clone()).unwrap_or_default();
        for (h, ips) in resolved {
            if h.contains('*') {
                continue;
            }
            for ip in ips {
                add_host_name(&mut hosts_map, ip, h.clone());
                if !h.contains('.') {
                    if let Some(dom) = &dns_cfg.domain {
                        add_host_name(&mut hosts_map, ip, format!("{}.{}", h, dom));
                    }
                }
            }
        }
    }

    let mut hosts_txt = String::from("# Generated by nfty — Auto-Synthesized VIP & Host Records\n");
    for (ip, names) in hosts_map {
        if !names.is_empty() {
            hosts_txt.push_str(&format!("{:<16} {}\n", ip, names.join(" ")));
        }
    }

    (conf, hosts_txt)
}

fn is_managed_dnsmasq(pid: u32) -> bool {
    let proc_path = format!("/proc/{}", pid);
    let exe_is_dnsmasq = fs::read_link(format!("{}/exe", proc_path))
        .ok()
        .and_then(|path| path.file_name().map(|name| name == "dnsmasq"))
        .unwrap_or(false);
    let uses_config = fs::read(format!("{}/cmdline", proc_path))
        .ok()
        .map(|cmdline| cmdline.split(|b| *b == 0).any(|arg| arg == DNSMASQ_CONF_PATH.as_bytes()))
        .unwrap_or(false);
    exe_is_dnsmasq && uses_config
}

pub fn dnsmasq_running_pid() -> Option<u32> {
    if let Ok(raw) = fs::read_to_string(DNSMASQ_PID_PATH) {
        if let Ok(pid) = raw.trim().parse::<u32>() {
            if is_managed_dnsmasq(pid) {
                return Some(pid);
            }
        }
    }
    if let Ok(entries) = fs::read_dir("/proc") {
        for entry in entries.flatten() {
            let name = entry.file_name();
            let s = name.to_string_lossy();
            if s.chars().all(|c| c.is_ascii_digit()) {
                if let Ok(pid) = s.parse::<u32>() {
                    if is_managed_dnsmasq(pid) {
                        return Some(pid);
                    }
                }
            }
        }
    }
    None
}

pub fn stop_dnsmasq_daemon() -> Result<()> {
    if let Some(pid) = dnsmasq_running_pid() {
        unsafe {
            if libc::kill(pid as i32, libc::SIGTERM) != 0 {
                return Err(std::io::Error::last_os_error())
                    .with_context(|| format!("Failed to stop dnsmasq {}", pid));
            }
        }
        for _ in 0..20 {
            if !is_managed_dnsmasq(pid) {
                break;
            }
            std::thread::sleep(Duration::from_millis(50));
        }
        if is_managed_dnsmasq(pid) {
            bail!("dnsmasq {} did not stop", pid);
        }
    }
    match fs::remove_file(DNSMASQ_PID_PATH) {
        Ok(()) => {}
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
        Err(e) => return Err(e).context("Failed to remove dnsmasq PID file"),
    }
    Ok(())
}

fn find_dnsmasq_binary() -> Option<&'static str> {
    for path in ["/usr/bin/dnsmasq", "/usr/sbin/dnsmasq", "/bin/dnsmasq", "/sbin/dnsmasq"] {
        if Path::new(path).exists() {
            return Some(path);
        }
    }
    None
}

const BLOCKLIST_REFRESH_INTERVAL: Duration = Duration::from_secs(24 * 60 * 60);

fn blocklist_needs_refresh(path: &str, force: bool) -> bool {
    if force {
        return true;
    }
    let Ok(meta) = fs::metadata(path) else {
        return true;
    };
    let Ok(modified) = meta.modified() else {
        return true;
    };
    match modified.elapsed() {
        Ok(age) => age >= BLOCKLIST_REFRESH_INTERVAL,
        Err(_) => true,
    }
}

fn blocklist_cache_has_domains(path: &Path) -> Result<bool> {
    let file = match fs::File::open(path) {
        Ok(file) => file,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(e) => return Err(e).with_context(|| format!("Failed to read {}", path.display())),
    };
    for line in BufReader::new(file).lines() {
        let line = line.with_context(|| format!("Failed to read {}", path.display()))?;
        if !normalize_blocklist_to_hosts(&line).is_empty() {
            return Ok(true);
        }
    }
    Ok(false)
}

/// Fetches or refreshes configured blocklists into `/data/dns/lists/<name>.hosts`.
/// Re-downloads remote lists automatically when missing, older than 24 hours, or when `force` is true.
/// Returns `(log_messages, any_file_changed)`.
pub fn sync_dns_blocklists(dns_cfg: &DnsConfig, force: bool) -> Result<(Vec<String>, bool)> {
    let mut logs = Vec::new();
    let mut changed = false;
    if dns_cfg.blocklists.is_empty() {
        return Ok((logs, changed));
    }
    fs::create_dir_all(DNS_LISTS_DIR).context("Failed to prepare DNS blocklist directory")?;
    for bl in &dns_cfg.blocklists {
        if !crate::ast::DnsBlocklist::valid_name(&bl.name) {
            bail!("Invalid DNS blocklist name '{}'", bl.name);
        }
        let dest = format!("{}/{}.hosts", DNS_LISTS_DIR, bl.name);
        let is_remote = bl.url.starts_with("http://") || bl.url.starts_with("https://");
        let valid_cache = blocklist_cache_has_domains(Path::new(&dest))?;
        if is_remote {
            if valid_cache && !blocklist_needs_refresh(&dest, force) {
                continue;
            }
        } else if bl.url == dest && valid_cache {
            continue;
        }

        let loaded: Result<String> = if is_remote {
            ureq::get(&bl.url)
                .timeout(Duration::from_secs(15))
                .call()
                .map_err(|e| anyhow::anyhow!("Failed to fetch blocklist '{}': {}", bl.name, e))
                .and_then(|response| response.into_string().context("Failed to read blocklist response"))
        } else {
            fs::read_to_string(&bl.url)
                .with_context(|| format!("Failed to read blocklist '{}'", bl.name))
        };
        let normalized = loaded.and_then(|body| {
            let normalized = normalize_blocklist_to_hosts(&body);
            if normalized.is_empty() {
                bail!("DNS blocklist '{}' contains no usable domains", bl.name);
            }
            Ok(normalized)
        });
        let normalized = match normalized {
            Ok(normalized) => normalized,
            Err(error) if !force && valid_cache => {
                eprintln!(
                    "nfty: DNS blocklist '{}' refresh failed; retaining cached list: {:#}",
                    bl.name, error
                );
                continue;
            }
            Err(error) => return Err(error),
        };
        let previous = match fs::read_to_string(&dest) {
            Ok(contents) => contents,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
            Err(e) => return Err(e).with_context(|| format!("Failed to read {}", dest)),
        };
        if previous != normalized || is_remote {
            crate::unikernel::write_atomic_with_mode(Path::new(&dest), normalized.as_bytes(), 0o644)
                .with_context(|| format!("Failed to update blocklist '{}'", bl.name))?;
            changed |= previous != normalized;
        }
        logs.push(format!(
            "Synced blocklist '{}' ({} domains) -> {}",
            bl.name, normalized.lines().count(), dest
        ));
    }
    Ok((logs, changed))
}

fn normalize_blocklist_to_hosts(raw: &str) -> String {
    let mut out = String::new();
    for line in raw.lines() {
        let trimmed = line.split('#').next().unwrap_or("").trim();
        if trimmed.is_empty() {
            continue;
        }
        let parts: Vec<&str> = trimmed.split_whitespace().collect();
        let candidate = if parts.len() >= 2 && (parts[0] == "0.0.0.0" || parts[0] == "127.0.0.1") {
            parts[1]
        } else if parts.len() == 1 {
            let d = parts[0].trim_start_matches("*.").trim_start_matches('.');
            if d.contains('.') && !d.contains('/') {
                d
            } else {
                continue;
            }
        } else {
            continue;
        };
        if let Ok(domain) = crate::parser::validate_host_mapping_name(candidate) {
            out.push_str(&format!("0.0.0.0 {}\n", domain));
        }
    }
    out
}

#[cfg(test)]
mod blocklist_tests {
    use super::*;

    #[test]
    fn empty_or_invalid_cached_lists_are_not_usable() {
        let path = std::env::temp_dir().join(format!(
            "nfty-blocklist-test-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        fs::write(&path, "# no domains\n0.0.0.0 0.0.0.0\n").unwrap();
        assert!(!blocklist_cache_has_domains(&path).unwrap());
        fs::write(&path, "0.0.0.0 ads.example\n").unwrap();
        assert!(blocklist_cache_has_domains(&path).unwrap());
        fs::remove_file(path).unwrap();
    }
}

/// Reconciles `/run/nfty-dnsmasq.conf` and `/run/nfty-dnsmasq.hosts` and starts/reloads `dnsmasq`.
pub fn reconcile_dnsmasq(cfg: &Config, st: Option<&AppState>) -> Result<String> {
    fs::create_dir_all("/run").context("Failed to prepare dnsmasq runtime directory")?;
    if !cfg.has_any_dns_enabled() {
        stop_dnsmasq_daemon()?;
        return Ok("DNS disabled".to_string());
    }

    let blocklists_changed = if let Some(dns_cfg) = &cfg.dns {
        sync_dns_blocklists(dns_cfg, false)?.1
    } else {
        false
    };

    let (conf_txt, hosts_txt) = compile_dnsmasq_config(cfg, st);
    let read_existing = |path: &str| -> Result<String> {
        match fs::read_to_string(path) {
            Ok(contents) => Ok(contents),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(String::new()),
            Err(e) => Err(e).with_context(|| format!("Failed to read {}", path)),
        }
    };
    let old_conf = read_existing(DNSMASQ_CONF_PATH)?;
    let old_hosts = read_existing(DNSMASQ_HOSTS_PATH)?;

    let conf_changed = old_conf != conf_txt;
    let hosts_changed = old_hosts != hosts_txt || blocklists_changed;

    if hosts_changed || !Path::new(DNSMASQ_HOSTS_PATH).exists() {
        crate::unikernel::write_atomic_with_mode(Path::new(DNSMASQ_HOSTS_PATH), hosts_txt.as_bytes(), 0o644)
            .with_context(|| format!("Failed to write {}", DNSMASQ_HOSTS_PATH))?;
    }
    if conf_changed || !Path::new(DNSMASQ_CONF_PATH).exists() {
        crate::unikernel::write_atomic_with_mode(Path::new(DNSMASQ_CONF_PATH), conf_txt.as_bytes(), 0o644)
            .with_context(|| format!("Failed to write {}", DNSMASQ_CONF_PATH))?;
    }

    let Some(bin) = find_dnsmasq_binary() else {
        bail!("dnsmasq is enabled but its binary is not installed");
    };

    if let Some(pid) = dnsmasq_running_pid() {
        if conf_changed {
            stop_dnsmasq_daemon()?;
        } else {
            if hosts_changed {
                unsafe {
                    if libc::kill(pid as i32, libc::SIGHUP) != 0 {
                        return Err(std::io::Error::last_os_error())
                            .context("Failed to reload dnsmasq hosts");
                    }
                }
                return Ok(format!("Reloaded dnsmasq hosts via SIGHUP (PID {})", pid));
            }
            return Ok(format!("dnsmasq running (PID {})", pid));
        }
    }

    let status = Command::new(bin)
        .args(["-C", DNSMASQ_CONF_PATH])
        .status()
        .with_context(|| format!("Failed to launch {}", bin))?;
    if !status.success() {
        bail!("dnsmasq exited with status {}", status);
    }
    let pid = dnsmasq_running_pid().context("dnsmasq started but its managed process was not found")?;
    Ok(format!("Started dnsmasq (PID {})", pid))
}

pub async fn run_dns_supervisor(shared: SharedState) {
    loop {
        if unsafe { libc::geteuid() == 0 } {
            {
                let st = shared.read().unwrap();
                let cfg = st.active_config().clone();
                if let Err(e) = reconcile_dnsmasq(&cfg, Some(&st)) {
                    eprintln!("nfty: DNS reconciliation failed: {:#}", e);
                }
            }
        }
        tokio::time::sleep(Duration::from_secs(5)).await;
    }
}

pub fn print_dns_status(shared: &SharedState) {
    let st = shared.read().unwrap();
    let cfg = st.active_config();
    let (conf_txt, hosts_txt) = compile_dnsmasq_config(cfg, Some(&st));
    let enabled = cfg.has_any_dns_enabled();
    let pid = dnsmasq_running_pid();
    let dns_cfg = cfg.dns.clone().unwrap_or_default();

    println!();
    println!("{}", "  nfty Programmable DNS Endpoint (dnsmasq)".bold().cyan());
    println!("  {}", "─".repeat(68).dimmed());
    let state_str = match (enabled, pid) {
        (true, Some(p)) => format!("{} (PID {})", "RUNNING".green().bold(), p),
        (true, None) => "ENABLED (staged / waiting for apply)".yellow().bold().to_string(),
        (false, _) => "DISABLED (run 'conf; dns; commit' to enable)".dimmed().to_string(),
    };
    println!("  {:<20} {}", "Daemon Status:".bold(), state_str);
    println!(
        "  {:<20} {}",
        "Local Domain:".bold(),
        dns_cfg.domain.as_deref().unwrap_or("(none)")
    );
    println!(
        "  {:<20} {} entries (all-servers: {}, health-aware: {})",
        "Cache & Mode:".bold(),
        dns_cfg.cache_size,
        if dns_cfg.all_servers { "on" } else { "off" },
        if dns_cfg.health_aware { "on" } else { "off" }
    );
    println!(
        "  {:<20} {}",
        "Upstreams:".bold(),
        if dns_cfg.upstreams.is_empty() {
            "(none)".to_string()
        } else {
            dns_cfg.upstreams.join(", ")
        }
    );

    let synth_lines: Vec<&str> = hosts_txt
        .lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
        .collect();
    println!(
        "  {:<20} {} auto-synthesized IPs (auto-vips: {}, auto-hosts: {})",
        "Synthesized Hosts:".bold(),
        synth_lines.len(),
        if dns_cfg.auto_vips { "on" } else { "off" },
        if dns_cfg.auto_hosts { "on" } else { "off" }
    );
    for l in synth_lines.iter().take(12) {
        println!("    {}", l.green());
    }
    if synth_lines.len() > 12 {
        println!("    ... and {} more", synth_lines.len() - 12);
    }

    if !dns_cfg.records.is_empty() {
        println!("  {:<20} {}", "Custom Records:".bold(), dns_cfg.records.len());
        for r in &dns_cfg.records {
            println!("    {}", r);
        }
    }
    if !dns_cfg.forward_zones.is_empty() {
        println!(
            "  {:<20} {}",
            "Forward Zones:".bold(),
            dns_cfg.forward_zones.len()
        );
        for fz in &dns_cfg.forward_zones {
            println!("    {}", fz);
        }
    }
    if !dns_cfg.nft_rules.is_empty() {
        println!(
            "  {:<20} {}",
            "Kernel nftset Rules:".bold(),
            dns_cfg.nft_rules.len()
        );
        for nr in &dns_cfg.nft_rules {
            println!("    {}", nr.to_string().yellow());
        }
    }
    if !dns_cfg.blocks.is_empty() || !dns_cfg.blocklists.is_empty() {
        println!(
            "  {:<20} {} inline rules, {} blocklists",
            "Sinkhole / Blocks:".bold(),
            dns_cfg.blocks.len(),
            dns_cfg.blocklists.len()
        );
    }
    let _ = conf_txt;
    println!();
}

/// Sends a standard RFC 1035 UDP A-record query to `127.0.0.1:53` (or falls back to config inspection)
pub fn run_dns_lookup_test(domain: &str, shared: &SharedState) {
    let clean = domain.trim().trim_end_matches('.').to_ascii_lowercase();
    println!(
        "  {} Testing DNS resolution for {}...",
        "→".cyan(),
        clean.bold()
    );

    if let Some((ips, elapsed)) = query_udp_a_record("127.0.0.1:53", &clean) {
        if ips.is_empty() {
            println!(
                "  {} Live reply from 127.0.0.1:53 in {:.2}ms: {} (NXDOMAIN / NODATA)",
                "✔".green(),
                elapsed.as_secs_f64() * 1000.0,
                "no A records".yellow()
            );
        } else {
            let ip_strs: Vec<String> = ips.iter().map(|i| i.to_string()).collect();
            println!(
                "  {} Live reply from 127.0.0.1:53 in {:.2}ms: {}",
                "✔".green(),
                elapsed.as_secs_f64() * 1000.0,
                ip_strs.join(", ").green().bold()
            );
        }
        return;
    }

    // Fallback: inspect compiled hosts/config if dnsmasq is not currently bound on 127.0.0.1:53
    let st = shared.read().unwrap();
    let cfg = st.active_config();
    let (_, hosts_txt) = compile_dnsmasq_config(cfg, Some(&st));
    for line in hosts_txt.lines() {
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        let parts: Vec<&str> = line.split_whitespace().collect();
        if parts.len() >= 2 && parts[1..].iter().any(|h| h.eq_ignore_ascii_case(&clean)) {
            println!(
                "  {} Matched synthesized host record: {} -> {}",
                "✔".green(),
                clean.bold(),
                parts[0].green().bold()
            );
            return;
        }
    }
    println!(
        "  {} No local synthesized record for '{}' (will forward to upstream DNS once dnsmasq is active)",
        "ℹ".blue(),
        clean
    );
}

fn query_udp_a_record(server: &str, domain: &str) -> Option<(Vec<Ipv4Addr>, Duration)> {
    let addr: SocketAddr = server.parse().ok()?;
    let sock = UdpSocket::bind("0.0.0.0:0").ok()?;
    sock.set_read_timeout(Some(Duration::from_millis(1200))).ok()?;

    let mut pkt = vec![
        0x12, 0x34, // ID
        0x01, 0x00, // Flags: standard query, RD=1
        0x00, 0x01, // QDCOUNT = 1
        0x00, 0x00, // ANCOUNT = 0
        0x00, 0x00, // NSCOUNT = 0
        0x00, 0x00, // ARCOUNT = 0
    ];
    for label in domain.split('.') {
        let bytes = label.as_bytes();
        if bytes.is_empty() || bytes.len() > 63 {
            return None;
        }
        pkt.push(bytes.len() as u8);
        pkt.extend_from_slice(bytes);
    }
    pkt.push(0x00);
    pkt.extend_from_slice(&[0x00, 0x01, 0x00, 0x01]); // QTYPE=A (1), QCLASS=IN (1)

    let start = Instant::now();
    sock.send_to(&pkt, addr).ok()?;
    let mut buf = [0u8; 512];
    let (n, _) = sock.recv_from(&mut buf).ok()?;
    let elapsed = start.elapsed();
    if n < 12 || buf[0] != 0x12 || buf[1] != 0x34 {
        return None;
    }
    let ancount = u16::from_be_bytes([buf[6], buf[7]]) as usize;
    let mut pos = 12;
    // Skip question section
    while pos < n && buf[pos] != 0 {
        if (buf[pos] & 0xC0) == 0xC0 {
            pos += 2;
            break;
        }
        pos += 1 + (buf[pos] as usize);
    }
    if pos < n && buf[pos] == 0 {
        pos += 1;
    }
    pos += 4; // QTYPE + QCLASS

    let mut ips = Vec::new();
    for _ in 0..ancount {
        if pos >= n {
            break;
        }
        if (buf[pos] & 0xC0) == 0xC0 {
            pos += 2;
        } else {
            let mut jumped = false;
            while pos < n && buf[pos] != 0 {
                if (buf[pos] & 0xC0) == 0xC0 {
                    pos += 2;
                    jumped = true;
                    break;
                }
                pos += 1 + (buf[pos] as usize);
            }
            if !jumped && pos < n && buf[pos] == 0 {
                pos += 1;
            }
        }
        if pos + 10 > n {
            break;
        }
        let rtype = u16::from_be_bytes([buf[pos], buf[pos + 1]]);
        let rdlen = u16::from_be_bytes([buf[pos + 8], buf[pos + 9]]) as usize;
        pos += 10;
        if pos + rdlen > n {
            break;
        }
        if rtype == 1 && rdlen == 4 {
            ips.push(Ipv4Addr::new(
                buf[pos],
                buf[pos + 1],
                buf[pos + 2],
                buf[pos + 3],
            ));
        }
        pos += rdlen;
    }
    Some((ips, elapsed))
}

pub fn handle_dns_cli_command(args: &[&str], shared: &SharedState) -> Result<()> {
    if args.is_empty()
        || args[0].eq_ignore_ascii_case("status")
        || args[0].eq_ignore_ascii_case("show")
    {
        print_dns_status(shared);
        return Ok(());
    }
    match args[0].to_ascii_lowercase().as_str() {
        "test" | "lookup" | "query" | "dig" => {
            if args.len() < 2 {
                bail!("Usage: dns test <domain>");
            }
            run_dns_lookup_test(args[1], shared);
        }
        "config" | "conf" | "dnsmasq" => {
            let st = shared.read().unwrap();
            let cfg = st.active_config();
            let (conf_txt, hosts_txt) = compile_dnsmasq_config(cfg, Some(&st));
            println!("{}", "# --- /run/nfty-dnsmasq.conf ---".bold().cyan());
            print!("{}", conf_txt);
            println!("\n{}", "# --- /run/nfty-dnsmasq.hosts ---".bold().cyan());
            print!("{}", hosts_txt);
        }
        "reload" | "flush" | "sync" => {
            let st = shared.read().unwrap();
            let cfg = st.active_config();
            let mut blocklist_changed = false;
            if let Some(dns_cfg) = &cfg.dns {
                let (logs, changed) = sync_dns_blocklists(dns_cfg, true)?;
                blocklist_changed = changed;
                for l in logs {
                    println!("  → {}", l);
                }
            }
            let msg = reconcile_dnsmasq(cfg, Some(&st))?;
            if blocklist_changed {
                let pid = dnsmasq_running_pid().context("dnsmasq is not running after blocklist refresh")?;
                if unsafe { libc::kill(pid as i32, libc::SIGHUP) } != 0 {
                    return Err(std::io::Error::last_os_error()).context("Failed to reload DNS blocklists");
                }
            }
            println!("  {} {}", "✔".green(), msg);
        }
        other => bail!(
            "Unknown dns command '{}'. Try: 'dns status', 'dns test <domain>', 'dns config', 'dns reload', or 'conf; dns' to configure.",
            other
        ),
    }
    Ok(())
}
